    // 1. Determine header row
    let headerRowIdx = preferredHeaderRow !== undefined ? preferredHeaderRow - 1 : -1;

    if (headerRowIdx < 0) {
      // Auto-detect best header row within first 6 rows
      let bestScore = -1;
      let bestRow = 0;

      const maxScan = Math.min(rawData.length, 6);
      for (let r = 0; r < maxScan; r++) {
        const row = rawData[r] || [];
        let score = 0;
        let nonNullCount = 0;

        for (let c = 0; c < row.length; c++) {
          const val = String(row[c] || '').trim();
          if (val) {
            nonNullCount++;
            const l = val.toLowerCase();
            if (l.includes('barcode') || l.includes('ean') || l.includes('c.barre') || l.includes('条码')) score += 50;
            if (l.includes('descrizione') || l.includes('prodotto') || l.includes('articolo') || l.includes('品名')) score += 35;
            if (l.includes('foto') || l.includes('image') || l.includes('immagine') || l.includes('pic') || l.includes('图片')) score += 35;
            if (l.includes('prezzo') || l.includes('price') || l.includes('qta') || l.includes('iva') || l.includes('codice')) score += 20;
          }
        }
        score += nonNullCount * 2;
        if (score > bestScore && nonNullCount >= 2) {
          bestScore = score;
          bestRow = r;
        }
      }
      headerRowIdx = bestRow;
    }

    const headerRow = rawData[headerRowIdx] || [];
    const maxCols = Math.max(...rawData.slice(0, 15).map((r) => (Array.isArray(r) ? r.length : 0)), headerRow.length);
    const dataRows = rawData.slice(headerRowIdx + 1, headerRowIdx + 35);
    const cols = [];

    for (let c = 0; c < maxCols; c++) {
      const val = String(headerRow[c] || '').trim();
      const letter = c < 26 ? String.fromCharCode(65 + c) : `${String.fromCharCode(64 + Math.floor(c / 26))}${String.fromCharCode(65 + (c % 26))}`;

      // Extract up to 2 distinct samples from data rows
      const samples: string[] = [];
      for (let r = 0; r < dataRows.length; r++) {
        const cellVal = String(dataRows[r]?.[c] ?? '').trim();
        if (cellVal && !samples.includes(cellVal)) {
          samples.push(cellVal.length > 25 ? cellVal.slice(0, 25) + '…' : cellVal);
          if (samples.length >= 2) break;
        }
      }

      cols.push({
        index: c + 1,
        letter,
        name: val ? val : `第 ${c + 1} 列 (${letter}列)`,
        hasOriginalName: !!val,
        sampleText: samples.length > 0 ? samples.join(', ') : '此列暂无数据',
      });
    }

    setTemplateColumns(cols);
    setTemplateHeaderRowIndex(headerRowIdx + 1);
    const startDataRow = headerRowIdx + 2;
    setTemplateStartDataRowIndex(startDataRow);
    setTemplatePreviewRows(rawData.slice(headerRowIdx, headerRowIdx + 10));

    // 2. Score each column based on BOTH HEADER and CELL VALUES (Deep statistical inference)
    let bestBarcodeCol = 1;
    let maxBarcodeScore = -1;

    let bestTitleCol = 0;
    let maxTitleScore = -1;

    let bestImageCol = 0;
    let maxImageScore = -1;

    cols.forEach((col) => {
      const cIdx = col.index - 1;
      const headerText = col.name.toLowerCase();

      let bScore = 0;
      let tScore = 0;
      let iScore = 0;

      // Header matching
      if (headerText.includes('barcode') || headerText.includes('bar code') || headerText.includes('c.barre') || headerText.includes('条形码') || headerText.includes('条码')) {
        bScore += 120;
      } else if (headerText.includes('ean') || headerText.includes('gtin') || headerText.includes('upc')) {
        bScore += 100;
      } else if (headerText.includes('codice a barre') || headerText.includes('cod.barre')) {
        bScore += 110;
      } else if (headerText === 'codice' || headerText.includes('cod.')) {
        bScore += 20;
      }

      if (headerText.includes('descrizione') || headerText.includes('descriz') || headerText.includes('denominazione') || headerText.includes('prodotto') || headerText.includes('品名') || headerText.includes('商品名称')) {
        tScore += 100;
      } else if (headerText.includes('title') || headerText.includes('name') || headerText.includes('名称') || headerText.includes('articolo')) {
        tScore += 60;
      }

      if (headerText.includes('foto') || headerText.includes('immagine') || headerText.includes('immagini') || headerText.includes('image') || headerText.includes('picture') || headerText.includes('pic') || headerText.includes('图片') || headerText.includes('图')) {
        iScore += 100;
      }

      // Cell values inspection (statistical inference)
      let numericBarcodeCount = 0;
      let textLengthSum = 0;
      let blankCount = 0;
      let totalValidCells = 0;

      dataRows.forEach((r) => {
        const val = String(r[cIdx] ?? '').trim();
        if (!val) {
          blankCount++;
          return;
        }
        totalValidCells++;
        const digitsOnly = val.replace(/[^0-9]/g, '');

        // Check if looks like barcode (8 to 14 digits)
        if (digitsOnly.length >= 8 && digitsOnly.length <= 14 && /^\d+$/.test(val)) {
          numericBarcodeCount++;
          if (val.startsWith('80') || val.startsWith('69') || val.startsWith('73') || val.startsWith('40') || val.startsWith('50') || val.startsWith('30')) {
            bScore += 25; // Common EAN prefixes
          } else {
            bScore += 15;
          }
        }

        textLengthSum += val.length;

        // Image clues in cells
        if (val.includes('.jpg') || val.includes('.png') || val.includes('http') || val.includes('IMAGE(')) {
          iScore += 25;
        }
      });

      if (totalValidCells > 0) {
        const barcodeRatio = numericBarcodeCount / totalValidCells;
        if (barcodeRatio > 0.5) {
          bScore += 200 * barcodeRatio;
        }

        const avgLength = textLengthSum / totalValidCells;
        if (avgLength > 10 && numericBarcodeCount === 0) {
          tScore += 50;
        }
      }

      // If column is completely blank, it's a great candidate for inserting images!
      if (blankCount >= dataRows.length * 0.8 && dataRows.length > 0) {
        iScore += 40;
      }

      if (bScore > maxBarcodeScore) {
        maxBarcodeScore = bScore;
        bestBarcodeCol = col.index;
      }
      if (tScore > maxTitleScore) {
        maxTitleScore = tScore;
        bestTitleCol = col.index;
      }
      if (iScore > maxImageScore) {
        maxImageScore = iScore;
        bestImageCol = col.index;
      }
    });

    // Fallbacks
    if (bestBarcodeCol) setTemplateBarcodeCol(bestBarcodeCol);
    if (bestTitleCol && bestTitleCol !== bestBarcodeCol) setTemplateTitleCol(bestTitleCol);

    if (bestImageCol && bestImageCol !== bestBarcodeCol) {
      setTemplateImageCol(bestImageCol);
    } else {
      const cand = cols.find((c) => c.index !== bestBarcodeCol && c.index !== bestTitleCol);
      setTemplateImageCol(cand ? cand.index : cols.length);
    }
